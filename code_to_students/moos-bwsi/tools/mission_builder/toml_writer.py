"""
toml_writer.py — scenario TOML serialiser for the BWSI mission builder
=======================================================================

Provides:
  write_toml(scenario_dict) → str   (complete TOML text ready to save)
  validate(scenario_dict)   → list[str]  (list of error messages; empty = OK)

The scenario_dict schema mirrors the TOML files consumed by gen_inspection.py,
gen_mcm.py, etc.  The builder web app constructs this dict from the user's
drawing session and calls write_toml() to persist it.

Supported mission types (scenario_dict["scenario"]["type"]):
  "inspection"  — pipeline survey (uses gen_inspection.py)
  "mcm"         — mine countermeasures (uses gen_mcm.py)
  "game"        — scavenger hunt (uses gen_mission.py)
  "gps_denied"  — GPS-denied beacon nav (uses gen_gps_denied.py)
"""

from __future__ import annotations

from typing import Any


# ---------------------------------------------------------------------------
# Primitive TOML emitters (no third-party dependency needed for writing)
# ---------------------------------------------------------------------------

def _indent(text: str, spaces: int) -> str:
    pad = " " * spaces
    return "\n".join(pad + line if line.strip() else line for line in text.splitlines())


def _toml_value(v: Any) -> str:
    """Serialise a Python value to its TOML literal representation."""
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, str):
        # Escape backslash and double-quote
        escaped = v.replace("\\", "\\\\").replace('"', '\\"')
        return f'"{escaped}"'
    if isinstance(v, float):
        # Always include decimal point so TOML parses as float
        s = f"{v}"
        return s if "." in s or "e" in s else f"{v:.1f}"
    if isinstance(v, int):
        return str(v)
    raise TypeError(f"Cannot serialise {type(v).__name__} to TOML")


def _write_section(name: str, data: dict) -> list[str]:
    """Emit a [section] block."""
    lines = [f"[{name}]"]
    for k, v in data.items():
        lines.append(f"{k} = {_toml_value(v)}")
    return lines


def _write_array_of_tables(name: str, items: list[dict]) -> list[str]:
    """Emit an [[array.of.tables]] block for each item in the list."""
    lines = []
    for item in items:
        lines.append(f"[[{name}]]")
        for k, v in item.items():
            if isinstance(v, list):
                # Nested list (e.g., pipeline points) → inline TOML array
                inner = ", ".join(
                    f"[{p[0]}, {p[1]}]" if isinstance(p, (list, tuple)) else _toml_value(p)
                    for p in v
                )
                lines.append(f"{k} = [{inner}]")
            else:
                lines.append(f"{k} = {_toml_value(v)}")
        lines.append("")
    return lines


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------

def write_toml(scenario_dict: dict) -> str:
    """
    Serialise a scenario dict to a well-formatted TOML string.

    The dict should follow this schema (all optional keys shown):

    {
      "scenario": {
          "name": str,
          "description": str,
          "type": "inspection" | "mcm" | "game" | "gps_denied",
          "tiff_file": str,          # optional
      },
      "origin": {"lat": float, "lon": float},
      "arena": {"vertices": [[x,y], ...]},   # local XY metres

      # inspection only:
      "pipelines": [{"label": str, "depth": float, "points": [[x,y],...]}, ...],
      "anomalies": [{"pipeline": str, "x": float, "y": float, "type": str}, ...],

      # mcm only:
      "mines": [{"label": str, "x": float, "y": float, "type": "hazard"|"benign"}, ...],

      "sensor": {...},     # mission-type-specific sensor params
      "scoring": {...},
      "survey": {...},     # mcm only

      "teams": [
          {
              "name": str,
              "color": str,
              "vehicles": [
                  {
                      "name": str,
                      "student_mode": "python" | "cpp",
                      "start_x": float,
                      "start_y": float,
                      "start_heading": int,
                      "max_speed": float,
                  }
              ],
          }
      ],

      # optional:
      "deployment": {
          "shoreside_host": str,
          "vehicle_hosts": {"alpha": str, "bravo": str, ...},
      },
    }
    """
    lines: list[str] = []

    mission_type = scenario_dict.get("scenario", {}).get("type", "unknown")

    # ---- Header comment ----
    lines.append(f"# BWSI AUVC — {scenario_dict.get('scenario', {}).get('name', 'Mission')} scenario")
    lines.append(f"# Mission type: {mission_type}")
    lines.append(f"# Generated by the BWSI Mission Builder")
    lines.append("")

    # ---- [scenario] ----
    lines.extend(_write_section("scenario", scenario_dict["scenario"]))
    lines.append("")

    # ---- [origin] ----
    lines.extend(_write_section("origin", scenario_dict["origin"]))
    lines.append("")

    # ---- [arena] ----
    arena = scenario_dict["arena"]
    lines.append("[arena]")
    inner = ", ".join(f"[{v[0]}, {v[1]}]" for v in arena["vertices"])
    lines.append(f"vertices = [{inner}]")
    lines.append("")

    # ---- Mission-type-specific geometry ----
    if mission_type == "inspection":
        if "pipelines" in scenario_dict:
            lines.extend(_write_array_of_tables("pipelines", scenario_dict["pipelines"]))
        if "anomalies" in scenario_dict:
            lines.extend(_write_array_of_tables("anomalies", scenario_dict["anomalies"]))

    elif mission_type == "mcm":
        if "mines" in scenario_dict:
            lines.extend(_write_array_of_tables("mines", scenario_dict["mines"]))

    # For game / gps_denied, geometry is encoded in the teams section.

    # ---- [sensor] ----
    if "sensor" in scenario_dict:
        lines.extend(_write_section("sensor", scenario_dict["sensor"]))
        lines.append("")

    # ---- [scoring] ----
    if "scoring" in scenario_dict:
        lines.extend(_write_section("scoring", scenario_dict["scoring"]))
        lines.append("")

    # ---- [survey] (mcm only) ----
    if "survey" in scenario_dict:
        lines.extend(_write_section("survey", scenario_dict["survey"]))
        lines.append("")

    # ---- [[teams]] ----
    for team in scenario_dict.get("teams", []):
        lines.append(f"[[teams]]")
        lines.append(f"name  = {_toml_value(team['name'])}")
        lines.append(f"color = {_toml_value(team['color'])}")
        lines.append("")
        for vehicle in team.get("vehicles", []):
            lines.append(f"  [[teams.vehicles]]")
            for k, v in vehicle.items():
                lines.append(f"  {k:<13} = {_toml_value(v)}")
            lines.append("")

    # ---- [deployment] (optional) ----
    if "deployment" in scenario_dict:
        dep = scenario_dict["deployment"]
        lines.append("[deployment]")
        if "shoreside_host" in dep:
            lines.append(f"shoreside_host = {_toml_value(dep['shoreside_host'])}")
        lines.append("")
        if "vehicle_hosts" in dep:
            lines.append("[deployment.vehicle_hosts]")
            for team_name, ip in dep["vehicle_hosts"].items():
                lines.append(f"{team_name} = {_toml_value(ip)}")
            lines.append("")

    return "\n".join(lines)


