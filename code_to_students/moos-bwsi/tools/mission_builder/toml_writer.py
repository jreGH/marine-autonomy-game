# Validation
# ---------------------------------------------------------------------------

def validate(scenario_dict: dict) -> list[str]:
    """
    Validate a scenario dict.  Returns a list of human-readable error strings;
    an empty list means the scenario is valid.

    Checks:
      - Required top-level keys present
      - Origin lat/lon in range
      - Arena has at least 3 vertices
      - Mission-type geometry present
      - At least one team with at least one vehicle
      - Vehicle start positions inside the arena bounding box
      - No duplicate vehicle names
    """
    errors: list[str] = []

    # ---- Required top-level keys ----
    for key in ("scenario", "origin", "arena", "teams"):
        if key not in scenario_dict:
            errors.append(f"Missing required key: '{key}'")

    if errors:
        return errors   # can't proceed without the basics

    sc = scenario_dict["scenario"]
    if "name" not in sc:
        errors.append("scenario.name is required")

    mission_type = sc.get("type", "")
    valid_types  = ("inspection", "mcm", "game", "gps_denied")
    if mission_type not in valid_types:
        errors.append(f"scenario.type must be one of {valid_types}; got '{mission_type}'")

    # ---- Origin ----
    origin = scenario_dict["origin"]
    lat = origin.get("lat")
    lon = origin.get("lon")
    if lat is None or lon is None:
        errors.append("origin must have lat and lon")
    else:
        if not (-90 <= lat <= 90):
            errors.append(f"origin.lat {lat} out of range [-90, 90]")
        if not (-180 <= lon <= 180):
            errors.append(f"origin.lon {lon} out of range [-180, 180]")

    # ---- Arena ----
    vertices = scenario_dict["arena"].get("vertices", [])
    if len(vertices) < 3:
        errors.append("arena.vertices must have at least 3 points")
    else:
        for i, v in enumerate(vertices):
            if len(v) != 2:
                errors.append(f"arena.vertices[{i}] must be [x, y]; got {v}")

    # ---- Mission-type geometry ----
    if mission_type == "inspection":
        if not scenario_dict.get("pipelines"):
            errors.append("inspection mission requires at least one [[pipelines]] entry")
    elif mission_type == "mcm":
        mines = scenario_dict.get("mines", [])
        if not mines:
            errors.append("mcm mission requires at least one [[mines]] entry")
        else:
            for i, m in enumerate(mines):
                for k in ("label", "x", "y", "type"):
                    if k not in m:
                        errors.append(f"mines[{i}] missing key '{k}'")
                if m.get("type") not in ("hazard", "benign", None):
                    errors.append(f"mines[{i}].type must be 'hazard' or 'benign'")

    # ---- Teams ----
    teams = scenario_dict.get("teams", [])
    if not teams:
        errors.append("At least one [[teams]] entry is required")

    seen_vehicle_names: set[str] = set()
    for ti, team in enumerate(teams):
        if "name" not in team:
            errors.append(f"teams[{ti}] missing 'name'")
        vehicles = team.get("vehicles", [])
        if not vehicles:
            errors.append(f"teams[{ti}] ({team.get('name','?')}) has no vehicles")
        for vi, v in enumerate(vehicles):
            for k in ("name", "start_x", "start_y"):
                if k not in v:
                    errors.append(
                        f"teams[{ti}].vehicles[{vi}] missing '{k}'"
                    )
            vname = v.get("name", "")
            if vname in seen_vehicle_names:
                errors.append(f"Duplicate vehicle name '{vname}'")
            seen_vehicle_names.add(vname)

            # Check start position inside arena bounding box
            if vertices and "start_x" in v and "start_y" in v:
                xs = [p[0] for p in vertices]
                ys = [p[1] for p in vertices]
                sx, sy = v["start_x"], v["start_y"]
                margin = 5.0
                if not (min(xs) - margin <= sx <= max(xs) + margin):
                    errors.append(
                        f"Vehicle '{vname}' start_x={sx} is outside arena "
                        f"x range [{min(xs)}, {max(xs)}]"
                    )
                if not (min(ys) - margin <= sy <= max(ys) + margin):
                    errors.append(
                        f"Vehicle '{vname}' start_y={sy} is outside arena "
                        f"y range [{min(ys)}, {max(ys)}]"
                    )

    return errors


